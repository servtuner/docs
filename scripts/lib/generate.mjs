export function generate(data) {
  const meta = json(join(data, 'meta.json'));
  const from = `Generated from servtuner commit \`${meta.sha.slice(0, 12)}\`.`;
  for (const p of ['api', 'schemas', 'cli.md', 'helm-values.md', 'configuration.md', 'runspec.md'])
    rmSync(join(OUT, p), { recursive: true, force: true });

  // API
  const api = json(join(data, 'openapi.json'));
  const nameOf = (n) =>
    n.replace(/^servtuner_api__(?:models__generated__(?:bundle__)?)?(.+?)(?:_schema)?__(\w+)$/, '$2 ($1)');
  const modelLink = (ref) => {
    const n = nameOf(ref.split('/').pop());
    return `[${cell(n)}](${BASE}/reference/api/models/#${slug(n)})`;
  };
  const bodyType = (content) =>
    Object.values(content ?? {}).map((c) => typeOf(c.schema ?? true, modelLink))[0] ?? 'None';
  const used = new Set();
  for (const [id, title, description, match] of RESOURCES) {
    const body = [from, ''];
    for (const [path, methods] of Object.entries(api.paths)) {
      if (!match.test(path)) continue;
      for (const [method, op] of Object.entries(methods)) {
        const key = `${method.toUpperCase()} ${path}`;
        used.add(key);
        const text = op.description ?? summaries[key];
        if (!text) throw new Error(`no summary for ${key}: add one to scripts/lib/generate.mjs`);
        body.push(`## \`${key}\``, '', cell(text), '');
        body.push(
          table(
            ['Parameter', 'In', 'Type', 'Required', 'Description'],
            (op.parameters ?? []).map((p) => [
              code(p.name),
              p.in,
              typeOf(p.schema, modelLink),
              p.required ? 'Yes' : 'No',
              [
                cell(p.description ?? ''),
                constraints(p.schema ?? {}),
                p.schema?.default !== undefined ? `Default: ${code(JSON.stringify(p.schema.default))}.` : '',
              ]
                .filter(Boolean)
                .join(' '),
            ]),
          ),
        );
        if (op.requestBody)
          body.push(
            `**Request body:** ${bodyType(op.requestBody.content)} (${Object.keys(op.requestBody.content).map(code).join(', ')})`,
            '',
          );
        body.push(
          table(
            ['Status', 'Meaning', 'Body'],
            Object.entries(op.responses).map(([s, r]) => [code(s), cell(r.description), bodyType(r.content)]),
          ),
        );
      }
    }
    page(`api/${id}.md`, title, description, body.join('\n'), 'tableOfContents:\n  maxHeadingLevel: 2\n');
  }
  const all = Object.entries(api.paths).flatMap(([p, m]) => Object.keys(m).map((x) => `${x.toUpperCase()} ${p}`));
  const missed = all.filter((k) => !used.has(k));
  if (missed.length) throw new Error(`operations without a page: ${missed.join(', ')}`);
  page(
    'api/models.md',
    'API models',
    'Every request and response model in the servtuner OpenAPI document.',
    [
      from,
      '',
      ...Object.entries(api.components.schemas)
        .sort(([a], [b]) => a.localeCompare(b))
        .flatMap(([n, s]) => [`## ${cell(nameOf(n))}`, '', shape(s, modelLink)]),
    ].join('\n'),
    'tableOfContents: false\n',
  );

  // Schemas
  const files = ['', 'bundle'].flatMap((d) =>
    readdirSync(join(data, 'schemas', d))
      .filter((f) => f.endsWith('.json'))
      .map((f) => [d, f]),
  );
  const schemaPath = (name) => (name === 'runspec' ? 'reference/runspec' : `reference/schemas/${name}`);
  for (const [dir, file] of files) {
    const s = json(join(data, 'schemas', dir, file));
    const name = file.replace('.schema.json', '');
    const link = (ref) => {
      const [f, pointer] = ref.split('#');
      const target = f ? f.split('/').pop().replace('.schema.json', '') : name;
      const anchor = pointer?.split('/').pop() ?? '';
      return `[${cell(anchor || target)}](${BASE}/${schemaPath(target)}/${anchor ? `#${slug(anchor)}` : ''})`;
    };
    const { description, ...rest } = s;
    const defs = Object.entries(s.definitions ?? s.$defs ?? {}).flatMap(([n, d]) => [
      `### ${cell(n)}`,
      '',
      shape(d, link),
    ]);
    const title = `${name} schema`;
    const intro = cell(description ?? '');
    page(
      `${schemaPath(name).replace('reference/', '')}.md`,
      name === 'runspec' ? 'RunSpec' : title,
      name === 'runspec'
        ? 'Every RunSpec field, its type, default and constraints.'
        : `Fields, types and constraints of the ${name} document.`,
      [
        intro,
        '',
        `Schema file: \`schema/json/${dir ? dir + '/' : ''}${file}\`. ${from}`,
        '',
        name === 'common' ? '' : '## Top level',
        '',
        name === 'common' ? '' : shape(rest, link),
        defs.length ? '## Definitions\n' : '',
        ...defs,
      ].join('\n'),
    );
  }
  page(
    'schemas/index.md',
    'Schemas',
    'Index of every JSON Schema that servtuner publishes.',
    [
      from,
      '',
      table(
        ['Schema', 'Location'],
        files.map(([d, f]) => {
          const n = f.replace('.schema.json', '');
          return [`[${n}](${BASE}/${schemaPath(n)}/)`, code(`schema/json/${d ? d + '/' : ''}${f}`)];
        }),
      ),
    ].join('\n'),
  );

  // CLI
  const cli = json(join(data, 'cli.json'));
  page(
    'cli.md',
    'CLI',
    'Every servtuner command, its flags and its exit codes.',
    [
      '`servtuner` is one Go binary. It runs as a Kubernetes Job or as a local process with the same command line.',
      '',
      from,
      '',
      '## Exit codes',
      '',
      'These apply to `servtuner run`. Other commands use the codes named in their help.',
      '',
      table(
        ['Code', 'Meaning'],
        [
          ['`0`', 'Succeeded'],
          ['`1`', 'The run failed'],
          ['`2`', 'Invalid RunSpec or flags'],
          ['`3`', 'Target unreachable'],
          ['`4`', 'The bundle could not be written. Wins when several apply.'],
        ],
      ),
      ...cli.flatMap((c) => [
        `## servtuner ${c.name}`,
        '',
        `${cell(c.short)}.`,
        '',
        '```text wrap',
        c.help.trim(),
        '```',
        '',
      ]),
    ].join('\n'),
  );

  // Helm values: comments and defaults from values.yaml
  const text = readFileSync(join(data, 'values.yaml'), 'utf8');
  const values = parse(text);
  const at = (path) => path.reduce((v, k) => v?.[k], values);
  const stack = [];
  let pending = [];
  const rows = {};
  const intro = {};
  for (const line of text.split('\n')) {
    const comment = /^\s*#\s?(.*)$/.exec(line);
    if (comment) {
      pending.push(comment[1].trim());
      continue;
    }
    const m = /^(\s*)([A-Za-z][\w]*):\s*(.*)$/.exec(line);
    if (!m) {
      if (!line.trim()) pending = [];
      continue;
    }
    const depth = m[1].length / 2;
    stack.length = depth;
    stack.push(m[2]);
    const inline = /(?:^|\s)#\s?(.*)$/.exec(m[3])?.[1] ?? '';
    const note = [pending.join(' '), inline].filter(Boolean).join(' ');
    pending = [];
    const value = at(stack);
    const top = stack[0];
    rows[top] ??= [];
    const bare = m[3].replace(/(?:^|\s)#.*$/, '').trim();
    if (bare === '' && value && typeof value === 'object') {
      if (stack.length === 1) intro[top] = note;
      else if (note) rows[top].push([code(stack.join('.')), 'section', cell(note)]);
      continue;
    }
    rows[top].push([code(stack.join('.')), code(JSON.stringify(value)), cell(note)]);
  }
  page(
    'helm-values.md',
    'Helm values',
    'Every value of the servtuner Helm chart with its default.',
    [
      from,
      '',
      ...Object.keys(values).flatMap((k) => [
        `## ${k}`,
        '',
        cell(intro[k] ?? ''),
        '',
        table(['Value', 'Default', 'Description'], rows[k] ?? []),
      ]),
    ].join('\n'),
  );

  // Environment
  const env = json(join(data, 'environment.json'));
  page(
    'configuration.md',
    'Configuration',
    'Environment variables read by the API, bench and the frontend.',
    [
      'The Helm chart sets these variables. Set them yourself when you run components without the chart.',
      '',
      from,
      '',
      table(
        ['Variable', 'Meaning', 'Values', 'Read by'],
        env.map((e) => [e.name, e.meaning, e.values, e.readBy].map((c, i) => (i === 0 ? c : cell(c)))),
      ),
      '## Data directory',
      '',
      'With the `file` storage backend, bench and the API resolve the data directory in this order: `SERVTUNER_DATA_DIR`, then `$XDG_DATA_HOME/servtuner`, then `~/.local/share/servtuner`.',
      '',
      '## Secrets directory',
      '',
      'bench reads each Secret named by a RunSpec as files in `<secrets dir>/<name>/<key>`. The directory is the `--secrets-dir` flag, then `SERVTUNER_SECRETS_DIR`, then `/etc/servtuner/secrets`.',
    ].join('\n'),
  );
}
