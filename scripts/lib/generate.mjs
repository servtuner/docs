// Writes the generated reference pages from src/data/servtuner.
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { parse } from 'yaml';

export const BASE = '';
const OUT = resolve('src/content/docs/reference');

export const cell = (text = '') =>
  String(text)
    .replace(/\s*\n\s*/g, ' ')
    .split(/(`[^`]*`)/)
    .map((part) =>
      part.startsWith('`')
        ? part.replaceAll('|', '\\|')
        : part.replace(/[<>|*_~[\]]/g, (c) => ({ '<': '&lt;', '>': '&gt;' })[c] ?? `\\${c}`),
    )
    .join('')
    .trim();
const code = (text) => (text === '' ? '' : `\`${String(text).replaceAll('|', '\\|')}\``);
const slug = (text) =>
  text
    .toLowerCase()
    .replace(/[^\w\- ]/g, '')
    .replaceAll(' ', '-');
const json = (path) => JSON.parse(readFileSync(path, 'utf8'));
const table = (head, rows) =>
  rows.length
    ? [
        `| ${head.join(' | ')} |`,
        `| ${head.map(() => '---').join(' | ')} |`,
        ...rows.map((r) => `| ${r.join(' | ')} |`),
        '',
      ].join('\n')
    : '';
const page = (path, title, description, body, extra = '') => {
  const file = join(OUT, path);
  mkdirSync(join(file, '..'), { recursive: true });
  writeFileSync(
    file,
    `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description)}\neditUrl: false\n${extra}---\n\n<!-- Generated by scripts/sync.mjs. Do not edit. -->\n\n${body}\n`,
  );
};

function typeOf(s, link) {
  if (s === undefined || s === true) return 'any';
  if (s.$ref) return link(s.$ref);
  if (s.allOf?.length === 1) return typeOf(s.allOf[0], link);
  if (s.const !== undefined) return code(JSON.stringify(s.const));
  if (s.enum) return s.enum.map((e) => code(JSON.stringify(e))).join(', ');
  const union = s.oneOf ?? s.anyOf;
  if (union && !s.properties) return union.map((u) => typeOf(u, link)).join(' or ');
  if (s.type === 'array') return `array of ${typeOf(s.items ?? true, link)}`;
  if (s.type === 'object' && s.additionalProperties && typeof s.additionalProperties === 'object' && !s.properties)
    return `map of ${typeOf(s.additionalProperties, link)}`;
  return code([s.type ?? 'any'].flat().join(' or '));
}
function constraints(s) {
  const out = [];
  for (const [key, label] of [
    ['minimum', '≥'],
    ['exclusiveMinimum', '>'],
    ['maximum', '≤'],
    ['exclusiveMaximum', '<'],
  ])
    if (typeof s[key] === 'number') out.push(`${label} ${s[key]}`);
  if (s.minLength > 1) out.push(`at least ${s.minLength} characters`);
  if (s.maxLength) out.push(`at most ${s.maxLength} characters`);
  if (s.minItems) out.push(`at least ${s.minItems} item${s.minItems > 1 ? 's' : ''}`);
  if (s.pattern) out.push(`pattern ${code(s.pattern)}`);
  return out.map((o) => (o.startsWith('pattern') ? o : cell(o))).join('; ');
}
function properties(s, link) {
  const required = new Set(s.required ?? []);
  return table(
    ['Field', 'Type', 'Required', 'Description'],
    Object.entries(s.properties ?? {}).map(([name, p]) => [
      code(name),
      typeOf(p, link),
      required.has(name) ? 'Yes' : 'No',
      [
        cell(p.description ?? ''),
        constraints(p),
        p.default !== undefined ? `Default: ${code(JSON.stringify(p.default))}.` : '',
      ]
        .filter(Boolean)
        .join(' '),
    ]),
  );
}
function shape(s, link) {
  const parts = [];
  if (s.description) parts.push(cell(s.description), '');
  if (s.properties) parts.push(properties(s, link));
  else parts.push(`Type: ${typeOf(s, link)}${constraints(s) ? ` (${constraints(s)})` : ''}`, '');
  if (s.properties && (s.oneOf || s.anyOf))
    parts.push('Exactly which fields are allowed together is restricted further by the schema.', '');
  return parts.join('\n');
}

